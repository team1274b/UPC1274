def _posterior_trajectories(noise="rounding", n=150, seed=3, prefix=None, files=None):
    """n trajectories drawn from a pooled posterior (reference integrator, full force model), cached in results/raw/.
    prefix: chain-file prefix (default: the CHAINS setting); files: list of (file label, C_L curve) pairs (default: 4 curves)."""
    prefix = CHAINS if prefix is None else prefix
    tag = "" if files is None else "_" + "_".join(f for f, _ in files)
    cache = ROOT / "results" / "raw" / f"fig_traj_{noise}_{prefix}{n}_{seed}{tag}.npz"
    if cache.exists():
        return list(np.load(cache)["trajs"])
    import sys
    sys.path.insert(0, str(ROOT / "scripts"))
    from run_stage5 import CURVES, FORCES, sample_params
    from penalty.constants import P0
    from penalty.integrate import simulate
    rng = np.random.default_rng(seed)
    trajs = []
    files = files or [(c, c) for c in CURVES]
    chains = {f: np.load(ROOT / "results" / "raw" / f"stage4_{noise}_{prefix}{f}.npz")["samples"] for f, _ in files}
    for k in range(n):
        f, c = files[k % len(files)]
        th = chains[f]
        v0, ball, p = sample_params(th[rng.integers(len(th))], c)
        sol, cr = simulate(P0, v0, FORCES, p, ball=ball)
        if cr is not None:
            trajs.append(sol.sol(np.linspace(0, cr.t, 120))[:3])
    np.savez_compressed(cache, trajs=np.array(trajs))
    return trajs


def _pooled_entries(noise="rounding", max_n=30000, seed=0, prefix=None):
    prefix = CHAINS if prefix is None else prefix
    curves = ["kray2014_re462", "kray2014_re_interp", "asai2007_re455", "asai2007_re_interp"]
    e = np.concatenate([np.load(ROOT / "results" / "raw" / f"stage4_{noise}_{prefix}{c}.npz")["entries"] for c in curves])
    e = e[np.all(np.isfinite(e), axis=1)][:, 1:3]
    rng = np.random.default_rng(seed)
    return e[rng.choice(len(e), min(max_n, len(e)), replace=False)]


def _hpd(entries, grid_y=(-0.5, 4.2), grid_z=(0.6, 3.0), n=220):
    """KDE on the goal plane: grid, density and the density levels enclosing 68 % / 95 % of the probability."""
    from scipy.stats import gaussian_kde
    kde = gaussian_kde(entries.T)
    Y, Z = np.meshgrid(np.linspace(*grid_y, n), np.linspace(*grid_z, int(n * 0.6)))
    D = kde(np.vstack((Y.ravel(), Z.ravel()))).reshape(Y.shape)
    at = np.sort(kde(entries[:4000].T))[::-1]
    return Y, Z, D, {q: at[int(q * len(at)) - 1] for q in (0.68, 0.95)}, (Y.ravel()[D.argmax()], Z.ravel()[D.argmax()])


