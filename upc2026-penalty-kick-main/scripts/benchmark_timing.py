"""Time evaluation of the simulation: cost of every computational building block and of the production runs.

Usage:  PYTHONPATH=src .venv/bin/python scripts/benchmark_timing.py [--repeat 7]

Part 1 (micro-benchmarks, one CPU thread, median of --repeat runs): one reference trajectory (DOP853), one trajectory with
frame impacts, the least-squares fits of Stages 1-3, one vectorised log-posterior evaluation of the whole walker ensemble,
and the propagation of a posterior to the goal plane.
Part 2 (production runs): wall-clock time of every MCMC chain, read from the run summaries (results/stage4, results/final),
converted to cost per walker-step, and the total CPU time of the project.
Part 3: projected wall-clock time on P parallel cores (chains and coverage trials are independent).
Writes results/timing.json and overleaf/tab_timing.tex.
"""
import os

os.environ.setdefault("OMP_NUM_THREADS", "1")
os.environ.setdefault("OPENBLAS_NUM_THREADS", "1")

import argparse
import json
import platform
import time
from dataclasses import replace
from pathlib import Path

import numpy as np

from penalty.bayes import Priors, initial_walkers, make_log_posterior, physics, unpack
from penalty.coefficients import LIFT_MODELS
from penalty.collision import FrameImpact, resolve
from penalty.constants import P0, TEST_CASE, Ball
from penalty.fastsim import Settings, crossings
from penalty.forces import AeroParams, drag, gravity, magnus, seam_force
from penalty.integrate import simulate
from penalty.inverse import fit

ROOT = Path(__file__).resolve().parents[1]
FORCES = [gravity, drag, magnus, seam_force]


def bench(f, repeat):
    ts = []
    for _ in range(repeat):
        t0 = time.perf_counter(); f(); ts.append(time.perf_counter() - t0)
    return float(np.median(ts))


def micro(repeat):
    spin = np.array([0.0, 0.0, -2 * np.pi * 5.0])
    p = replace(AeroParams(), spin=spin)
    v0 = np.array([30.3, 9.2, 6.9])
    st = Settings(LIFT_MODELS["kray2014_re462"])
    rng = np.random.default_rng(0)
    lp = make_log_posterior(st, priors=Priors(spin_prior="kick"))
    walkers = initial_walkers(128, rng, priors=Priors(spin_prior="kick"))
    post = initial_walkers(10000, rng, priors=Priors(spin_prior="kick"))
    r_post = P0 + np.array([0.0, 0.95, 0.0])                       # shifted so that the shot clips the inside of the post
    out = {
        "trajectory_dop853_s": bench(lambda: simulate(P0, v0, FORCES, p), repeat),
        "trajectory_with_frame_impact_s": bench(lambda: resolve(r_post, v0, FORCES, p, ball=Ball(), imp=FrameImpact()), repeat),
        "fit_stage1_s": bench(lambda: fit(TEST_CASE, [gravity], AeroParams()), repeat),
        "fit_stage3_s": bench(lambda: fit(TEST_CASE, [gravity, drag, magnus], AeroParams(), fit_spin=True), repeat),
        "log_posterior_128_walkers_s": bench(lambda: lp(walkers), repeat),
        "goal_plane_10000_samples_s": bench(lambda: crossings(P0, *unpack(post), st, **physics(post)), max(2, repeat // 3)),
    }
    out["log_posterior_per_walker_us"] = out["log_posterior_128_walkers_s"] / 128 * 1e6
    out["goal_plane_per_sample_us"] = out["goal_plane_10000_samples_s"] / 10000 * 1e6
    return out


def production():
    rows = []
    for path, kind in ((ROOT / "results" / "stage4", "stage4"), (ROOT / "results" / "final", "final")):
        for f in sorted(path.glob("summary_*.json")):
            d = json.load(open(f))
            cfg = d["config"]; ch = cfg["chains"]
            convs = []
            if kind == "stage4":
                convs += [(k, v["convergence"]) for k, v in d["nominal"].items()]
            else:
                for sp, rep in d["by_spin_prior"].items():
                    convs += list(rep["convergence"].items())
            convs += [(k, v["convergence"]) for k, v in d["sensitivity"].items()]
            for label, c in convs:
                rows.append({"run": f"{kind}_{cfg['noise']}", "chain": label, "runtime_s": c["runtime_s"],
                             "walker_steps": ch["nwalkers"] * ch["nsteps"],
                             "us_per_walker_step": c["runtime_s"] / (ch["nwalkers"] * ch["nsteps"]) * 1e6})
    return rows


def write_table(m, rows, cores):
    total = sum(r["runtime_s"] for r in rows)
    L = ["% AUTO-GENERATED by scripts/benchmark_timing.py (short version)",
         "\\begin{tabular}{@{}lr@{}}\\toprule", "Task (one CPU thread unless stated) & time\\\\\\midrule",
         f"one trajectory to the goal plane, adaptive DOP853 & \\SI{{{1e3 * m['trajectory_dop853_s']:.0f}}}{{ms}}\\\\",
         f"one trajectory with a frame impact & \\SI{{{1e3 * m['trajectory_with_frame_impact_s']:.0f}}}{{ms}}\\\\",
         f"one trajectory in the vectorised RK4 sampler & \\SI{{{m['log_posterior_per_walker_us']:.0f}}}{{\\micro s}}\\\\",
         f"all production chains, CPU time & \\SI{{{total / 3600:.1f}}}{{h}}\\\\",
         f"all production chains, wall clock on {cores[0]} cores & \\SI{{{proj(rows, cores[0]) / 60:.0f}}}{{min}}\\\\"]
    L.append("\\bottomrule\\end{tabular}")
    (ROOT / "overleaf" / "tab_timing.tex").write_text("\n".join(L) + "\n")


def proj(rows, p):
    """Greedy (longest first) scheduling of all independent chains on p cores."""
    load = np.zeros(p)
    for t in sorted((r["runtime_s"] for r in rows), reverse=True):
        load[np.argmin(load)] += t
    return float(load.max())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repeat", type=int, default=7)
    a = ap.parse_args()
    m = micro(a.repeat)
    rows = production()
    cores = (11, 64, 256)
    report = {"machine": {"cpu": platform.processor() or platform.machine(), "python": platform.python_version(),
                          "load_average_at_benchmark": os.getloadavg()},
              "micro_s": m, "production_chains": rows,
              "projected_wall_clock_s": {p: proj(rows, p) for p in cores}}
    (ROOT / "results" / "timing.json").write_text(json.dumps(report, indent=1))
    write_table(m, rows, cores)
    for k, v in m.items():
        print(f"  {k:34s} {v:.4g}")
    print(f"  production CPU time {sum(r['runtime_s'] for r in rows) / 3600:.1f} h over {len(rows)} chains; "
          f"projected wall clock {', '.join(f'{p} cores: {proj(rows, p) / 60:.0f} min' for p in cores)}")


if __name__ == "__main__":
    main()
